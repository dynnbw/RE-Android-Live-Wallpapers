package com.reandroid.wallpaper.noisefield;

import android.content.Context;

import com.reandroid.gles.GLESScene;
import com.reandroid.plugin.BasePluginEngine;
import com.reandroid.plugin.WallpaperPluginHost;

public class NoiseFieldEngine extends BasePluginEngine {

    public NoiseFieldEngine(Context context, WallpaperPluginHost host) {
        super(context, host);
    }

    @Override
    protected GLESScene createScene(int width, int height, Context context) {
        return new NoiseFieldGL(width, height, context);
    }
}
