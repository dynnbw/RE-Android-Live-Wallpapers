package com.reandroid.wallpaper.galaxy4;

import android.content.Context;

import com.reandroid.gles.GLESScene;
import com.reandroid.plugin.BasePluginEngine;
import com.reandroid.plugin.WallpaperPluginHost;

public class Galaxy4Engine extends BasePluginEngine {

    public Galaxy4Engine(Context context, WallpaperPluginHost host) {
        super(context, host);
    }

    @Override
    protected GLESScene createScene(int width, int height, Context context) {
        return new Galaxy4GL(width, height, context);
    }
}
