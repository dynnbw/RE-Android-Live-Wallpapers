package com.reandroid.wallpaper.fireworks;

import android.content.Context;

import com.reandroid.gles.GLESScene;
import com.reandroid.plugin.BasePluginEngine;
import com.reandroid.plugin.WallpaperPluginHost;

public class FireworksEngine extends BasePluginEngine {

    public FireworksEngine(Context context, WallpaperPluginHost host) {
        super(context, host);
    }

    @Override
    protected GLESScene createScene(int width, int height, Context context) {
        return new FireworksGL(width, height, context);
    }
}
