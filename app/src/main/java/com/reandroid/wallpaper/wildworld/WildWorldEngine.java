package com.reandroid.wallpaper.wildworld;

import android.content.Context;

import com.reandroid.gles.GLESScene;
import com.reandroid.plugin.BasePluginEngine;
import com.reandroid.plugin.WallpaperPluginHost;

public class WildWorldEngine extends BasePluginEngine {
    public WildWorldEngine(Context context, WallpaperPluginHost host) {
        super(context, host);
    }

    @Override
    protected GLESScene createScene(int width, int height, Context context) {
        return new WildWorldGL(width, height, context);
    }
}
