package com.reandroid.wallpaper.plant3d;

import android.content.Context;

import com.reandroid.gles.GLESScene;
import com.reandroid.plugin.BasePluginEngine;
import com.reandroid.plugin.WallpaperPluginHost;

public class Plant3DEngine extends BasePluginEngine {

    public Plant3DEngine(Context context, WallpaperPluginHost host) {
        super(context, host);
    }

    @Override
    protected GLESScene createScene(int width, int height, Context context) {
        return new Plant3DGL(width, height, context);
    }
}
