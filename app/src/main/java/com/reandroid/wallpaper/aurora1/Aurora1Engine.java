package com.reandroid.wallpaper.aurora1;

import android.content.Context;

import com.reandroid.gles.GLESScene;
import com.reandroid.plugin.BasePluginEngine;
import com.reandroid.plugin.WallpaperPluginHost;

public class Aurora1Engine extends BasePluginEngine {

    public Aurora1Engine(Context context, WallpaperPluginHost host) {
        super(context, host);
    }

    @Override
    protected GLESScene createScene(int width, int height, Context context) {
        return new Aurora1GL(context, width, height);
    }
}
